const path = require('node:path');
const fs = require('node:fs');
const tls = require('node:tls');

function databaseTlsOptions(hostname) {
  if (process.env.DATABASE_CA_CERT) return { rejectUnauthorized: true, ca: process.env.DATABASE_CA_CERT };
  if (hostname.endsWith('.pooler.supabase.com') || hostname.endsWith('.supabase.co')) {
    const supabaseCa = fs.readFileSync(path.join(__dirname, 'certs/supabase-root-2021.crt'), 'utf8');
    return { rejectUnauthorized: true, ca: [...tls.rootCertificates, supabaseCa] };
  }
  return { rejectUnauthorized: true };
}


// PostgreSQL is used on Render; SQLite keeps local development self-contained.
async function openDatabase() {
  const postgres = !!process.env.DATABASE_URL;
  if (process.env.NODE_ENV === 'production' && !postgres) {
    throw new Error('DATABASE_URL is required in production. Configure the Supabase session pooler URI.');
  }
  let pool, sqlite;
  if (postgres) {
    const url = new URL(process.env.DATABASE_URL);
    if (!['postgres:', 'postgresql:'].includes(url.protocol) || url.password.includes('YOUR-PASSWORD')) {
      throw new Error('DATABASE_URL must contain a complete PostgreSQL connection URI.');
    }
    // Do not let URI parameters override certificate verification.
    for (const key of ['sslmode', 'sslcert', 'sslkey', 'sslrootcert']) url.searchParams.delete(key);
    const { Pool } = require('pg');
    pool = new Pool({ connectionString: url.toString(), max: 5, connectionTimeoutMillis: 10000,
      ssl: databaseTlsOptions(url.hostname) });
    pool.on('error', err => console.error('Database connection error:', err.code || 'unknown'));
  } else {
    const { DatabaseSync } = require('node:sqlite');
    const dir = process.env.DATA_DIR || path.join(__dirname, '.data');
    fs.mkdirSync(dir, { recursive: true });
    sqlite = new DatabaseSync(path.join(dir, 'fusion.sqlite'));
    sqlite.exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON;');
  }
  function sql(text) {
    let index = 0;
    if (postgres) text = text.replace(/\?/g, () => '$' + ++index);
    return postgres ? text.replace(/\b(users|sessions|games|duels|game_modes|mode_scores|friendships|messages)\b/g, 'fusion.$1') : text;
  }
  function connection(client) {
    return {
      async all(text, params = []) {
        return postgres ? (await client.query(sql(text), params)).rows : sqlite.prepare(text).all(...params);
      },
      async one(text, params = []) { return (await this.all(text, params))[0]; },
      async run(text, params = []) {
        return postgres ? client.query(sql(text), params) : sqlite.prepare(text).run(...params);
      },
      async lockUser(id) { if (postgres) await client.query('SELECT id FROM fusion.users WHERE id=$1 FOR UPDATE', [id]); }
    };
  }
  const db = connection(pool);
  // Serialize SQLite transactions because callbacks use async/await on one connection.
  let queue = Promise.resolve();
  db.transaction = async callback => {
    if (postgres) {
      const client = await pool.connect();
      try { await client.query('BEGIN'); const result = await callback(connection(client)); await client.query('COMMIT'); return result; }
      catch (error) { await client.query('ROLLBACK'); throw error; }
      finally { client.release(); }
    }
    const operation = queue.then(async () => {
      sqlite.exec('BEGIN IMMEDIATE');
      try { const result = await callback(db); sqlite.exec('COMMIT'); return result; }
      catch (error) { sqlite.exec('ROLLBACK'); throw error; }
    });
    queue = operation.catch(() => {});
    return operation;
  };
  db.close = () => postgres ? pool.end() : sqlite.close();
  try {
    if (postgres) await pool.query('CREATE SCHEMA IF NOT EXISTS fusion');
    const id = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
    await db.run(`CREATE TABLE IF NOT EXISTS users(id ${id}, username TEXT NOT NULL, username_key TEXT NOT NULL UNIQUE, salt TEXT NOT NULL, hash TEXT NOT NULL, best INTEGER NOT NULL DEFAULT 0)`);
    await db.run('CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user_id INTEGER NOT NULL REFERENCES users(id),expires BIGINT NOT NULL)');
    await db.run('CREATE TABLE IF NOT EXISTS games(user_id INTEGER PRIMARY KEY REFERENCES users(id),board TEXT NOT NULL,score INTEGER NOT NULL,moves INTEGER NOT NULL,won INTEGER NOT NULL DEFAULT 0)');
    await db.run('CREATE TABLE IF NOT EXISTS duels(code TEXT PRIMARY KEY,host_id INTEGER NOT NULL REFERENCES users(id),guest_id INTEGER REFERENCES users(id),state TEXT NOT NULL,expires BIGINT NOT NULL)');
    await db.run('CREATE TABLE IF NOT EXISTS game_modes(user_id INTEGER PRIMARY KEY REFERENCES users(id),meta TEXT NOT NULL)');
    await db.run('CREATE TABLE IF NOT EXISTS mode_scores(user_id INTEGER NOT NULL REFERENCES users(id),mode TEXT NOT NULL,best INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(user_id,mode))');
    await db.run('CREATE TABLE IF NOT EXISTS friendships(low_id INTEGER NOT NULL REFERENCES users(id),high_id INTEGER NOT NULL REFERENCES users(id),sender_id INTEGER NOT NULL REFERENCES users(id),accepted INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(low_id,high_id))');
    await db.run(`CREATE TABLE IF NOT EXISTS messages(id ${id},sender_id INTEGER NOT NULL REFERENCES users(id),recipient_id INTEGER NOT NULL REFERENCES users(id),body TEXT NOT NULL,duel_code TEXT,created_at BIGINT NOT NULL)`);
    await db.run('CREATE INDEX IF NOT EXISTS messages_pair_idx ON messages(sender_id,recipient_id,id)');
    await db.run('CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions(expires)');
    if (postgres) {
      // Private schema: do not expose password hashes or session data through the Data API.
      await pool.query('REVOKE ALL ON SCHEMA fusion FROM PUBLIC');
      await pool.query('ALTER TABLE fusion.users ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.sessions ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.games ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.duels ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.game_modes ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.friendships ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.messages ENABLE ROW LEVEL SECURITY; ALTER TABLE fusion.mode_scores ENABLE ROW LEVEL SECURITY');
    }
  } catch (error) { await db.close(); throw error; }
  return db;
}
module.exports = { openDatabase, databaseTlsOptions };
